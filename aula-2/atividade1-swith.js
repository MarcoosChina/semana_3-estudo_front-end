let conceito = "A";

switch (conceito) {
    case "A":
        console.log("Excelente");
        break;
    case "B":
        console.log("Bom");
        break;
    case "C":
        console.log("Regular");
        break;
    case "D":
        console.log("Reprovado");
        break;
    default:
        console.log("Conceito inválido");
}