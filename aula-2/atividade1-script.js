let recebe = 13.564;
console.log('Arredondando para cima: ', Math.ceil(recebe)); // Arredonda para cima
console.log('Arredondar para baixo: ', Math.floor(recebe)); // Arredonda para baixo
console.log('Arredondando para o número mais próximo: ', Math.round(recebe)); // Arredonda para o número mais próximo
console.log('Número toFixed: ', recebe.toFixed(2)); // Formata o número com 2 casas decimais