let receba = 20;
console.log('A raiz quadrada:' , Math.sqrt(receba)); // Calcula a raiz quadrada
console.log('O quadrado deste número é: ' , Math.pow(receba, 2)); // Calcula o quadrado do número
console.log('Este número dividido por 3 contendo 3 casas decimais:' , (receba / 3).toFixed(3)); // Divide o número por 3 e formata com 3 casas decimais