const arrayexemplo = [1, 2, 3, 4, 5];

console.log(arrayexemplo[0]); // Acessando o primeiro elemento do array
console.log(arrayexemplo[2]); // Acessando o terceiro elemento do array

arrayexemplo.push(6);
console.log(arrayexemplo); // Exibindo o array atualizado após adicionar um elemento

arrayexemplo.pop();
console.log(arrayexemplo); // Exibindo o array atualizado após remover o último elemento

arrayexemplo.shift();
console.log(arrayexemplo); // Exibindo o array atualizado após remover o primeiro elemento